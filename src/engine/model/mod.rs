//! Модель документа и графа сцены (аналог объектной модели Figma).
//!
//! - `types` — вспомогательные типы: цвета, заливки, обводки, эффекты, автолейаут.
//! - `nodes` — ключи арен (`slotmap`) и разновидности нод (`NodeKind`, `ShapeKind`).
//! - `scene` — `SceneNode` и `SceneGraph` (арена + обходы + мутации).
//! - `document` — `Page`, `Document` и глобальные именованные стили.
//!
//! Модуль аддитивный: текущий прототип (`engine::scene`) продолжает работать
//! без изменений; миграция рендеров/контроллера на новую модель — отдельный шаг.
//! Поэтому публичные типы пока не достижимы из `main` — гасим dead_code
//! до момента интеграции (см. TODO-миграция).

#![allow(dead_code)]

pub mod document;
pub mod nodes;
pub mod scene;
pub mod types;
